"""CHIM OStim Bridge by SaurOff - assembles the Nexus release.

Run with any Python 3.8+ (python3 -I build.py [release dir]) after make_esp.py has
written build/CHIMOStimBridge.esp and compile_scripts.ps1 has compiled build/Scripts.
See BUILDING.md. Produces:
  build/cob_ostim_bridge-<version>.dwpkg   CHIM server plugin package (schema 4)
  <release dir>/CHIM OStim Bridge-<version>.zip   FOMOD archive for Nexus / Vortex
"""
import hashlib, json, os, re, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
RELEASE_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "release")
NAME = "cob_ostim_bridge"

version = re.search(r'const COB_VERSION = "([^"]+)"', open(os.path.join(ROOT, "server", NAME, "cob_lib.php")).read()).group(1)
for path, pattern in [("fomod/info.xml", r'MachineVersion="([^"]+)"'),
                      ("src/Scripts/Source/COB_Config.psc", r'Return "(\d+\.\d+\.\d+)"'),
                      ("server/" + NAME + "/manifest.json", r'"version": "([^"]+)"')]:
    found = re.search(pattern, open(os.path.join(ROOT, path), encoding="utf-8").read()).group(1)
    assert found == version, f"{path} says {found}, cob_lib.php says {version}"


def build_dwpkg(out):
    src = os.path.join(ROOT, "server", NAME)
    files = {}
    for name in sorted(os.listdir(src)):
        full = os.path.join(src, name)
        if os.path.isfile(full):
            files["server/" + name] = open(full, "rb").read()
    manifest = {"schema_version": 4, "name": NAME, "version": version, "author": "SaurOff",
                "description": "CHIM OStim Bridge server plugin", "server": {"mutable_paths": []}}
    files["manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    sums = "".join(f"{hashlib.sha256(data).hexdigest()}  {p}\n" for p, data in sorted(files.items()))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p, data in sorted(files.items()):
            z.writestr(p, data)
        z.writestr("checksums.sha256", sums)


def copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(src, dst)


stage = os.path.join(ROOT, "build", "stage")
shutil.rmtree(stage, ignore_errors=True)
pkg = os.path.join(ROOT, "build", f"{NAME}-{version}.dwpkg")
build_dwpkg(pkg)

core = os.path.join(stage, "00 Core")
copy(os.path.join(ROOT, "build", "CHIMOStimBridge.esp"), os.path.join(core, "CHIMOStimBridge.esp"))
for s in ["COB_Config", "COB_Bridge", "COB_Events", "COB_MCM"]:
    copy(os.path.join(ROOT, "build", "Scripts", s + ".pex"), os.path.join(core, "Scripts", s + ".pex"))
    copy(os.path.join(ROOT, "src", "Scripts", "Source", s + ".psc"), os.path.join(stage, "20 Source", "Source", "Scripts", s + ".psc"))
for f in ["config.json", "settings.ini"]:
    copy(os.path.join(ROOT, "mcm", f), os.path.join(core, "MCM", "Config", "CHIMOStimBridge", f))
# MCM translations, one file per game language (generated by localize.py)
tdir = os.path.join(ROOT, "mcm", "translations")
for f in sorted(os.listdir(tdir)):
    copy(os.path.join(tdir, f), os.path.join(core, "Interface", "Translations", f))
copy(pkg, os.path.join(core, "CHIM", "server-plugins", NAME, version + ".dwpkg"))

tools = os.path.join(stage, "10 Server Tools", "CHIM OStim Bridge Server Tools")
for f in ["Install-ServerPlugin.bat", "Install-ServerPlugin.ps1", "Uninstall-ServerPlugin.bat", "Uninstall-ServerPlugin.ps1"]:
    copy(os.path.join(ROOT, "server", f), os.path.join(tools, f))
for f in sorted(os.listdir(os.path.join(ROOT, "server", NAME))):
    copy(os.path.join(ROOT, "server", NAME, f), os.path.join(tools, NAME, f))

for f in ["info.xml", "ModuleConfig.xml"]:
    copy(os.path.join(ROOT, "fomod", f), os.path.join(stage, "fomod", f))
for f in ["README.txt", "CHANGELOG.txt"]:
    copy(os.path.join(ROOT, "docs", f), os.path.join(stage, f))

os.makedirs(RELEASE_DIR, exist_ok=True)
out = os.path.join(RELEASE_DIR, f"CHIM OStim Bridge-{version}.zip")
if os.path.exists(out):
    os.remove(out)
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for dirpath, _, names in os.walk(stage):
        for n in sorted(names):
            full = os.path.join(dirpath, n)
            z.write(full, os.path.relpath(full, stage).replace(os.sep, "/"))
print("version", version)
print("package", pkg)
print("release", out, os.path.getsize(out), "bytes")
